// types/app.ts: the SHAPES of the app's data, written as TypeScript types.
//
// Nothing here runs. These descriptions let TypeScript check, before the app
// even starts, that we use the data correctly (e.g. that we don't treat a
// price as text or misspell a field name). Most of them mirror a database
// table row or what a database function sends back; field names use the
// database's snake_case spelling so rows can be used as they arrive.
//
// Imported (with `import type`, which disappears from the final JavaScript)
// by api.ts, roles.ts, expiry.ts, useStoreData.ts, AuthContext.tsx and most
// components and pages.
//
// Reading the syntax:
//   interface X { ... }   the fields an object of type X has
//   name?: string         the `?` means the field may be missing
//   string | null         "either a string or null" (null = no value)
//   'a' | 'b'             only these exact texts are allowed
//   interface B extends A { ... }   B has everything A has, plus more
//   type X = ...          gives a name to a type (an alias)
//
// One product in the catalog: a row of the `products` table.
export interface Product {
  id: number;
  sku: string;
  // Generated by the database when the product is added; never edited.
  barcode: string;
  name: string;
  // Who makes it, e.g. "Bear Brand" or "Gardenia". Shown above the name.
  // null for products saved before brands existed (migration 20261102130000).
  brand?: string | null;
  category: string;
  // Selling price, in pesos.
  price: number;
  // What one unit cost the store, in pesos (used for profit and losses).
  // Optional because only ADMINS can see it: the database hides it from
  // everyone else, and useStoreData only fills it in for admins.
  cost?: number;
  // Units on the shelf, kept up to date by the database. In lists that come
  // from getInventoryOverview() it is replaced with the SELLABLE count.
  stock_quantity: number;
  // At or below this many units, Inventory marks the product "low stock".
  reorder_level: number;
  // Web address of the product picture (Supabase Storage), if it has one.
  image_url?: string | null;
  // Short text shown under the product on the POS menu. Optional.
  description?: string | null;
  created_at?: string;
  updated_at?: string;
}

// One delivery of a product: a row of the `product_batches` table.
// Stock is tracked per batch so we know which units expire when.
export interface ProductBatch {
  id: number;
  // Which product this batch is of (products.id).
  product_id: number;
  // Made by the database: 'B-12' for received stock; older stock may have
  // 'INITIAL-<id>' (starting stock of a new product) or 'LEGACY-<id>'.
  batch_code: string;
  quantity_received: number;
  quantity_remaining: number;
  // 'YYYY-MM-DD' text, or null when the expiry isn't known (starting stock).
  expiry_date: string | null;
  //   active  = on the shelf and can be sold (if not past its date)
  //   expired = removed by expiry processing (0 left)
  //   spoiled = written off down to 0 (damaged or spoiled)
  //   manual  = allowed by the database, but nothing in the app sets it
  status: 'active' | 'expired' | 'spoiled' | 'manual';
  // Date-and-time texts filled in by the database.
  received_at?: string;
  expired_at?: string | null;
  created_at?: string;
}

// A product plus its live stock numbers: one row from the database function
// get_product_inventory() (see api.getInventoryOverview). "Today" is the
// Philippine date.
export interface ProductInventorySummary extends Product {
  // Units that can be sold: active batches not yet past their date.
  available_quantity: number;
  // Units past their date that expiry processing hasn't removed yet.
  expired_quantity: number;
  // UNITS (not batches) expiring in the next 7 days; these sell at 15% off.
  near_expiry_count: number;
  // Soonest expiry date among the sellable batches ('YYYY-MM-DD'), or null.
  earliest_expiry_date: string | null;
  // Yes/no flags for warnings: some expired stock is still on the shelf /
  // some stock expires within 7 days.
  has_expired_batches: boolean;
  expires_soon: boolean;
}

// What the "Receive stock" form sends to api.receiveStock().
export interface ReceiveStockInput {
  product_id: number;
  quantity: number;
  // 'YYYY-MM-DD'; must be after today.
  expiry_date: string;
}

// The two reasons an admin can write stock off. ('expired' also exists in
// the database's spoilage log, but only expiry processing writes it.)
export type StockWriteOffKind = 'damaged' | 'spoiled';

// What the "Write off" form sends to api.writeOffStock().
export interface WriteOffStockInput {
  batch_id: number;
  quantity: number;
  kind: StockWriteOffKind;
  // A short explanation, saved in the spoilage log.
  reason: string;
}

// ── Analytics (everything below comes from get_admin_sales_analytics) ──────
// "Revenue" always means money actually taken in (orders.final_amount):
// after near-expiry markdowns and after the part paid with points.
//
// One day on the 30-day sales chart. date is 'YYYY-MM-DD'.
export interface SalesTrendPoint {
  date: string;
  revenue: number;
}

// One month of sales this year so far. month is 'YYYY-MM'.
export interface MonthlyRevenuePoint {
  month: string;
  revenue: number;
}

// One slice of the payment-method chart (this year): name is 'Cash', 'Card'
// or 'Loyalty Points', value is the revenue paid that way.
export interface PaymentMixPoint {
  name: string;
  value: number;
}

// One of the 10 best-selling products this year, by revenue. Each line's
// revenue is reduced by its share of any points discount on that order.
export interface TopProductPoint {
  name: string;
  revenue: number;
  quantity: number;
}

// Money in and money lost for one period (a day, week or month). Worked out by
// profit_and_loss_between() in
// supabase/migrations/20261101120000_profit_and_loss_analytics.sql.
export interface ProfitLossTotals {
  orders: number;
  revenue: number;              // money actually taken in (after near-expiry markdowns and points)
  cost_of_goods: number;        // what the sold items cost the store
  gross_profit: number;         // revenue - cost_of_goods
  near_expiry_discount: number; // given away by the 15% near-expiry markdown
  points_discount: number;      // paid for with loyalty points
  expired_loss: number;         // stock thrown out because it expired (at cost)
  spoiled_loss: number;         // written off as spoiled (at cost)
  damaged_loss: number;         // written off as damaged (at cost)
  total_losses: number;         // expired + spoiled + damaged
  net_profit: number;           // gross_profit - total_losses
}

// The same totals for one specific day, week (Monday to Sunday) or month.
export interface ProfitLossPeriod extends ProfitLossTotals {
  start: string; // first day of the period, 'YYYY-MM-DD'
}

// The payment mix and top products for one date range (Philippine days,
// `from` to `to`, both included): the answer of get_sales_breakdown() (see
// api.getSalesBreakdown). The Analytics tab asks for whatever range or single
// day / week / month is showing. Admins only.
export interface SalesBreakdown {
  from: string; // 'YYYY-MM-DD'
  to: string; // 'YYYY-MM-DD'
  // Largest first; `orders` = how many sales used that method.
  payment_mix: (PaymentMixPoint & { orders: number })[];
  // The 10 products that brought in the most in the range.
  top_products: TopProductPoint[];
}

// Profit & loss for one range, cut into hours, days or months: the answer of
// get_profit_loss_series() (see api.getProfitLossSeries). The Analytics tab
// uses it to browse a day (hour by hour), a month (day by day) or a year
// (month by month). Each period's `start` is its first moment: a date
// ('2026-11-02') for days and months, a date and time ('2026-11-02T08:00')
// for hours. `totals` is the whole range. Admins only.
export interface ProfitLossSeries {
  from: string;
  to: string;
  step: 'hour' | 'day' | 'month';
  periods: ProfitLossPeriod[];
  totals: ProfitLossTotals;
}

// Everything the Analytics tab shows: the whole answer of
// get_admin_sales_analytics() (see api.getSalesAnalytics). Admins only.
export interface SalesAnalytics {
  // Revenue for today, this week (since Monday), this month and this year,
  // by the Philippine calendar.
  today_revenue: number;
  week_revenue: number;
  month_revenue: number;
  year_revenue: number;
  // Revenue of every sale ever recorded (all time).
  net_revenue: number;
  // One entry per day for the last 30 days.
  thirty_day_trend: SalesTrendPoint[];
  // One entry per month from January up to this month.
  monthly_revenue: MonthlyRevenuePoint[];
  payment_mix: PaymentMixPoint[];
  top_products: TopProductPoint[];
  // Value (at cost) of all stock thrown out this year: expired, spoiled, damaged.
  spoilage_losses: number;
  // Optional: only there once the 20261101120000 migration has been applied.
  daily_breakdown?: ProfitLossPeriod[];   // last 30 days
  weekly_breakdown?: ProfitLossPeriod[];  // last 12 weeks
  monthly_breakdown?: ProfitLossPeriod[]; // last 12 months
  year_summary?: ProfitLossTotals;        // this year so far
}

// The three roles. A person can hold several (see src/lib/roles.ts).
export type AppRole = 'admin' | 'cashier' | 'customer';

// A loyalty member: a `customer` table row joined with that person's `users`
// row. Built by api.getCustomers(). Every account is a member, admins too.
export interface LoyaltyMember {
  id: string;
  email: string;
  // Falls back to the email when the person has no name saved.
  name?: string | null;
  phone?: string | null;
  role: AppRole;
  // e.g. 'LOY-000042'; given out automatically by the database.
  loyalty_id: string | null;
  // Current points balance (1 point = ₱5 off).
  loyalty_points: number;
  created_at?: string;
}

// Another name for the same type; the POS and pages call members "customers".
export type Customer = LoyaltyMember;

// One line of the points audit trail: a row of the `loyalty_logs` table.
// Written only by the checkout function in the database.
export interface LoyaltyLog {
  id: number;
  // The member's user id.
  customer_id: string;
  order_id: number | null;
  // Positive when points were EARNED, negative when REDEEMED (e.g. -10).
  points_changed: number;
  // e.g. "Earned 2 points on order #15 (₱250.00 paid)".
  reason?: string | null;
  type: 'EARNED' | 'REDEEMED';
  created_at: string;
}

// One line in the POS basket: the product (all its fields) plus how many
// and which batch they come from.
export interface CartItem extends Product {
  quantity: number;
  // The batch the units come from, or null to let the database use the
  // soonest-expiring stock (the default).
  batch_id: number | null;
  // Copies of the chosen batch's code and expiry date, for showing on screen
  // and for the 15% preview (null when no batch was chosen).
  batch_code: string | null;
  batch_expiry: string | null;
}

// Everything POS.tsx hands to api.processCheckout() to save a sale.
// Prices are NOT sent: the database looks them up itself.
export interface CheckoutPayload {
  cart: CartItem[];
  // The member's user id. Every sale needs one (the database refuses null).
  customerId: string | null;
  pointsToRedeem: number;
  paymentMethod: 'Cash' | 'Card' | 'Loyalty Points';
  // The cash handed over (for working out change), or null when not paying cash.
  cashReceived: number | null;
}

// One line on the receipt, as saved in the database (order_items).
export interface CheckoutReceiptItem {
  product_name: string;
  quantity: number;
  // The price actually charged per unit (after any 15% markdown).
  unit_price: number;
  // unit_price × quantity.
  subtotal: number;
  // The product's normal price.
  original_unit_price: number;
  // How much the markdown took off this line, in pesos.
  near_expiry_discount: number;
  // 15 if this line was marked down, otherwise 0.
  near_expiry_percent_off: number;
  // Only filled in when a batch was chosen for this line; null when the
  // database picked the stock itself (soonest expiry first).
  batch_code: string | null;
}

// What process_pos_checkout() sends back after a successful sale; shown by
// Receipt.tsx. Money is in pesos. The totals fit together like this:
//   subtotal (normal prices) - near_expiry_savings = total_amount
//   total_amount - points_discount = total_paid
export interface CheckoutReceipt {
  // Always true here: a failed sale comes back as an error instead.
  success: true;
  order_id: number;
  created_at: string;
  member_name: string;
  member_email: string;
  member_loyalty_id: string | null;
  // The member's points AFTER this sale (redeemed taken off, earned added).
  points_balance: number;
  // 1 point per full ₱100 of total_paid.
  points_earned: number;
  points_redeemed: number;
  subtotal: number;
  near_expiry_savings: number;
  total_amount: number;
  // ₱5 per point redeemed, never more than total_amount.
  points_discount: number;
  total_paid: number;
  // `CheckoutPayload['paymentMethod']` reuses that field's type:
  // 'Cash' | 'Card' | 'Loyalty Points'.
  payment_method: CheckoutPayload['paymentMethod'];
  // Only for Cash; null for Card and Loyalty Points.
  cash_received: number | null;
  change: number | null;
  items: CheckoutReceiptItem[];
}

// What the "Add product" form sends to api.addProduct(). No id or barcode:
// the database creates those. stock_quantity is the starting stock.
export interface NewProductInput {
  sku: string;
  name: string;
  brand: string;
  category: string;
  price: number;
  cost: number;
  stock_quantity: number;
  reorder_level: number;
  image_url?: string | null;
  description?: string | null;
}

// What the "Edit product" form sends to api.updateProduct(). Same as above
// but WITHOUT stock_quantity: stock only changes through batches (receiving,
// writing off, selling, expiry), so the counts always match the batches.
export interface UpdateProductInput {
  sku: string;
  name: string;
  brand: string;
  category: string;
  price: number;
  cost: number;
  reorder_level: number;
  image_url?: string | null;
  description?: string | null;
}

// One line of a saved sale (a row of the `order_items` table).
// list_price, unit_cost and product_name are FROZEN at the moment of sale
// (a database trigger copies them from the product), so editing the product
// later never changes past orders or past profit. They can be null only on a
// database where that migration hasn't been applied yet.
export interface OrderLine {
  id: number;
  product_id: number;
  // Which delivery the units came from (null for stock without batches).
  batch_id: number | null;
  quantity: number;
  // The price actually charged per unit (15% lower for near-expiry stock).
  unit_price: number;
  // unit_price × quantity.
  subtotal: number;
  // The product's normal price when it was sold.
  list_price: number | null;
  // What one unit cost the store when it was sold (admins only).
  unit_cost: number | null;
  // The product's name when it was sold.
  product_name: string | null;
}

// A saved sale (a row of the `orders` table) with its lines.
// Built by api.getOrders(); only admins can read orders.
export interface Order {
  id: number;
  created_at: string;
  // The member's user id (every sale is on a member's account).
  customer_id: string | null;
  // The basket total after near-expiry markdowns, BEFORE points.
  total_amount: number;
  // How many pesos loyalty points took off.
  discount_amount: number;
  // What the customer actually paid: total_amount - discount_amount.
  final_amount: number;
  payment_method: string;
  points_redeemed: number;
  items: OrderLine[];
}
