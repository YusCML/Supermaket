create extension if not exists pg_cron with schema pg_catalog;

do $$
declare
  existing_job record;
begin
  for existing_job in
    select jobid from cron.job where jobname = 'process-expired-product-batches'
  loop
    perform cron.unschedule(existing_job.jobid);
  end loop;

  perform cron.schedule(
    'process-expired-product-batches',
    '5 16 * * *',
    'select public._process_expired_batches();'
  );
end;
$$;
