-- Track stock by batch and record quantities removed after expiry.
create sequence if not exists public.product_batch_code_seq;

create table public.product_batches (
  id bigint generated by default as identity primary key,
  product_id integer not null references public.products(id) on delete restrict,
  batch_code text not null,
  quantity_received integer not null check (quantity_received > 0),
  quantity_remaining integer not null check (
    quantity_remaining >= 0 and quantity_remaining <= quantity_received
  ),
  expiry_date date,
  status text not null default 'active'
    check (status in ('active', 'expired', 'spoiled', 'manual')),
  received_at timestamptz not null default now(),
  expired_at timestamptz,
  created_at timestamptz not null default now(),
  unique (product_id, batch_code)
);

create index product_batches_sellable_idx
  on public.product_batches (product_id, expiry_date)
  where status = 'active' and quantity_remaining > 0;

create table public.spoilage_logs (
  id bigint generated by default as identity primary key,
  batch_id bigint not null references public.product_batches(id) on delete restrict,
  product_id integer not null references public.products(id) on delete restrict,
  quantity integer not null check (quantity > 0),
  unit_cost numeric(10, 2) not null check (unit_cost >= 0),
  loss_amount numeric(12, 2) not null check (loss_amount >= 0),
  expired_at timestamptz not null,
  created_at timestamptz not null default now()
);

create index spoilage_logs_created_at_idx on public.spoilage_logs (created_at);

alter table public.product_batches enable row level security;
alter table public.spoilage_logs enable row level security;

grant select on public.product_batches, public.spoilage_logs to authenticated;
revoke insert, update, delete on public.product_batches, public.spoilage_logs
  from anon, authenticated;

create policy "Admins can view product batches"
  on public.product_batches for select to authenticated
  using (public.is_admin());

create policy "Admins can view spoilage logs"
  on public.spoilage_logs for select to authenticated
  using (public.is_admin());

-- Preserve existing stock as one legacy batch until staff receive batches with
-- known expiry dates. Legacy expiry is unknown, so it remains NULL.
insert into public.product_batches (
  product_id, batch_code, quantity_received, quantity_remaining
)
select id, 'LEGACY-' || id::text, stock_quantity, stock_quantity
  from public.products
 where stock_quantity > 0
on conflict (product_id, batch_code) do nothing;

-- Products added through the existing catalog form can start with stock. Keep
-- that stock traceable even when expiry information is not provided there.
create or replace function public.create_initial_product_batch()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.stock_quantity > 0 then
    insert into public.product_batches (
      product_id, batch_code, quantity_received, quantity_remaining
    )
    values (
      new.id, 'INITIAL-' || new.id::text, new.stock_quantity, new.stock_quantity
    );
  end if;
  return new;
end;
$$;

drop trigger if exists products_create_initial_batch on public.products;
create trigger products_create_initial_batch
  after insert on public.products
  for each row execute function public.create_initial_product_batch();

create or replace function public.receive_stock(
  p_product_id integer,
  p_quantity integer,
  p_expiry_date date,
  p_batch_code text default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  new_batch_code text;
begin
  if not public.is_admin() then
    raise exception 'Only admins can receive stock.';
  end if;
  if p_product_id is null or p_quantity is null or p_quantity <= 0 then
    raise exception 'Choose a product and enter a quantity greater than zero.';
  end if;
  if p_expiry_date is null
     or p_expiry_date < (now() at time zone 'Asia/Manila')::date then
    raise exception 'The expiry date must be today or later.';
  end if;
  perform 1 from public.products where id = p_product_id for update;
  if not found then
    raise exception 'That product no longer exists.';
  end if;

  new_batch_code := nullif(btrim(p_batch_code), '');
  if new_batch_code is null then
    new_batch_code := 'B-' || nextval('public.product_batch_code_seq')::text;
  end if;

  insert into public.product_batches (
    product_id, batch_code, quantity_received, quantity_remaining, expiry_date
  )
  values (p_product_id, new_batch_code, p_quantity, p_quantity, p_expiry_date);

  update public.products
     set stock_quantity = stock_quantity + p_quantity,
         updated_at = now()
   where id = p_product_id;

  return jsonb_build_object('success', true, 'batch_code', new_batch_code);
end;
$$;

create or replace function public.get_product_inventory()
returns table (
  id integer,
  sku varchar,
  barcode varchar,
  name varchar,
  category varchar,
  price numeric,
  cost numeric,
  stock_quantity integer,
  reorder_level integer,
  created_at timestamp,
  updated_at timestamp,
  available_quantity integer,
  expired_quantity integer,
  near_expiry_count integer,
  earliest_expiry_date date,
  has_expired_batches boolean,
  expires_soon boolean
)
language sql
stable
security definer
set search_path = ''
as $$
  select p.id, p.sku, p.barcode, p.name, p.category, p.price, p.cost,
         p.stock_quantity, p.reorder_level, p.created_at, p.updated_at,
         coalesce(sum(b.quantity_remaining) filter (
           where b.status = 'active'
             and (b.expiry_date is null
               or b.expiry_date > (now() at time zone 'Asia/Manila')::date)
         ), 0)::integer as available_quantity,
         coalesce(sum(b.quantity_remaining) filter (
           where b.status = 'active'
             and b.expiry_date <= (now() at time zone 'Asia/Manila')::date
         ), 0)::integer as expired_quantity,
         coalesce(sum(b.quantity_remaining) filter (
           where b.status = 'active'
             and b.expiry_date > (now() at time zone 'Asia/Manila')::date
             and b.expiry_date <= (now() at time zone 'Asia/Manila')::date + 7
         ), 0)::integer as near_expiry_count,
         min(b.expiry_date) filter (
           where b.status = 'active'
             and b.quantity_remaining > 0
             and b.expiry_date > (now() at time zone 'Asia/Manila')::date
         ) as earliest_expiry_date,
         coalesce(bool_or(
           b.status = 'active'
           and b.quantity_remaining > 0
           and b.expiry_date <= (now() at time zone 'Asia/Manila')::date
         ), false) as has_expired_batches,
         coalesce(bool_or(
           b.status = 'active'
           and b.quantity_remaining > 0
           and b.expiry_date > (now() at time zone 'Asia/Manila')::date
           and b.expiry_date <= (now() at time zone 'Asia/Manila')::date + 7
         ), false) as expires_soon
    from public.products p
    left join public.product_batches b on b.product_id = p.id
   where public.is_staff()
   group by p.id
   order by p.id;
$$;

create or replace function public._process_expired_batches()
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  processed_count integer;
begin
  with expired as (
    select b.id, b.product_id, b.quantity_remaining
      from public.product_batches b
     where b.status = 'active'
       and b.quantity_remaining > 0
       and b.expiry_date <= (now() at time zone 'Asia/Manila')::date
     for update skip locked
  ), marked as (
    update public.product_batches b
       set quantity_remaining = 0,
           status = 'expired',
           expired_at = now()
      from expired e
     where b.id = e.id
    returning e.id, e.product_id, e.quantity_remaining
  )
  insert into public.spoilage_logs (
    batch_id, product_id, quantity, unit_cost, loss_amount, expired_at
  )
  select e.id, e.product_id, e.quantity_remaining, p.cost,
         e.quantity_remaining * p.cost, now()
    from marked e
    join public.products p on p.id = e.product_id;

  get diagnostics processed_count = row_count;

  update public.products p
     set stock_quantity = coalesce((
           select sum(b.quantity_remaining)::integer
             from public.product_batches b
            where b.product_id = p.id and b.status = 'active'
              and (b.expiry_date is null
                or b.expiry_date > (now() at time zone 'Asia/Manila')::date)
         ), 0),
         updated_at = now()
   where p.stock_quantity is distinct from coalesce((
           select sum(b.quantity_remaining)::integer
             from public.product_batches b
            where b.product_id = p.id and b.status = 'active'
              and (b.expiry_date is null
                or b.expiry_date > (now() at time zone 'Asia/Manila')::date)
         ), 0);

  return processed_count;
end;
$$;

create or replace function public.process_expired_batches()
returns integer
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.is_admin() then
    raise exception 'Only admins can process expired stock.';
  end if;
  return public._process_expired_batches();
end;
$$;

